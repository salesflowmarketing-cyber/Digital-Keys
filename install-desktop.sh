#!/usr/bin/env bash
# Digital Keys - install desktop integration (Linux / freedesktop)
# Run: ./install-desktop.sh
#
# Installs: hicolor icons, a .desktop launcher, and a `digital-keys` wrapper
# in ~/.local/bin. The launcher runs the native CustomTkinter GUI (`dk gui`).
#
# Uninstall:
#   rm -f ~/.local/share/applications/digital-keys.desktop \
#         ~/.local/bin/digital-keys
#   rm -rf ~/.local/share/icons/hicolor/*/apps/digital-keys.png

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
NAME="digital-keys"
VENV="$HERE/digital-keys-venv"
STATIC="$HERE/digital_keys/static"

APPS_DIR="$HOME/.local/share/applications"
ICON_ROOT="$HOME/.local/share/icons/hicolor"
BIN_DIR="$HOME/.local/bin"
DESKTOP_FILE="$APPS_DIR/${NAME}.desktop"
WRAPPER="$BIN_DIR/${NAME}"

say() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mFAIL:\033[0m %s\n' "$*" >&2; exit 1; }

[ -f "$HERE/pyproject.toml" ] || die "run this from the Digital Keys repo root"

# --- 1. virtualenv -----------------------------------------------------------
if [ ! -x "$VENV/bin/dk" ]; then
    say "Creating virtualenv and installing..."
    python3 -m venv "$VENV"
    "$VENV/bin/pip" install --quiet --upgrade pip
    "$VENV/bin/pip" install --quiet -e "$HERE"
fi
[ -x "$VENV/bin/dk" ] || die "dk entry point missing from $VENV"

# --- 2. icons ----------------------------------------------------------------
say "Installing icons..."
mkdir -p "$ICON_ROOT"
for size in 32 48 64 128 256; do
    src="$STATIC/icon_${size}.png"
    [ -f "$src" ] || continue
    dst_dir="$ICON_ROOT/${size}x${size}/apps"
    mkdir -p "$dst_dir"
    install -m 644 "$src" "$dst_dir/${NAME}.png"
done

if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f -t "$ICON_ROOT" 2>/dev/null || true
fi

# --- 3. terminal wrapper -----------------------------------------------------
say "Creating launcher wrapper..."
mkdir -p "$BIN_DIR"
cat > "$WRAPPER" <<WRAP
#!/usr/bin/env bash
# Digital Keys launcher (generated by install-desktop.sh)
exec "$VENV/bin/dk" gui "\$@"
WRAP
chmod 755 "$WRAPPER"

# --- 4. desktop entry --------------------------------------------------------
say "Creating desktop entry..."
mkdir -p "$APPS_DIR"
cat > "$DESKTOP_FILE" <<DESKTOP
[Desktop Entry]
Version=1.5
Type=Application
Name=Digital Keys
GenericName=Credential Vault
Comment=Encrypted local vault and AI agent broker
Exec=$WRAPPER
Icon=$NAME
Terminal=false
Categories=Utility;Security;Network;
Keywords=password;vault;api;key;credentials;manager;agent;
StartupNotify=true
StartupWMClass=$NAME
DESKTOP
chmod 644 "$DESKTOP_FILE"

if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS_DIR" 2>/dev/null || true
fi

echo
say "✅ Digital Keys desktop integration installed"
echo
echo "   App menu:  Digital Keys"
echo "   Terminal:  $WRAPPER"
echo "   CLI:       $VENV/bin/dk"
echo
echo "   Uninstall:"
echo "     rm -f $DESKTOP_FILE $WRAPPER"
echo "     rm -f $ICON_ROOT/*/apps/${NAME}.png"
